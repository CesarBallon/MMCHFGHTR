export const FIGHTERS: readonly FighterDefinition[] = Object.freeze(
  seeds.map(
    ([
      id,
      displayName,
      archetype,
      homeStage,
      version,
      walkSpeed,
      jumpSpeed,
      powerPermille,
      defensePermille,
      renderHeight,
      first,
      second,
    ]): FighterDefinition => ({
      schemaVersion: 1,
      id,
      displayName,
      archetype,
      homeStage,
      theme: `${displayName}Theme.mp3`,
      assets: artwork(id, version),
      stats: {
        walkSpeed,
        jumpSpeed,
        health: 1000,
        powerPermille,
        defensePermille,
        renderHeight,
      },
      moves: [
        ...normals(),
        special(first, "special1"),
        special(second, "special2"),
      ],
      specialMoveIds: [first[0], second[0]],
    }),
  ),
);

export const FIGHTERS_BY_ID = Object.freeze(
  Object.fromEntries(FIGHTERS.map((fighter) => [fighter.id, fighter])),
) as Readonly<Record<FighterId, FighterDefinition>>;
