import type {
  FighterDefinition,
  FighterId,
  MoveDefinition,
} from "./fighter-schema";

type Special = readonly [
  id: string,
  name: string,
  atlas: string,
  damage: number,
  startup: number,
  active: number,
  recovery: number,
  hitstun: number,
];
type FighterSeed = readonly [
  FighterId,
  string,
  FighterDefinition["archetype"],
  FighterDefinition["homeStage"],
  number,
  number,
  number,
  number,
  number,
  number,
  Special,
  Special,
];

function combatMove(
  id: string,
  displayName: string,
  kind: MoveDefinition["kind"],
  command: MoveDefinition["command"],
  atlas: string,
  startFrame: number,
  frameCount: number,
  startupFrames: number,
  activeFrames: number,
  recoveryFrames: number,
  damage: number,
  hitstunFrames: number,
): MoveDefinition {
  return {
    id,
    displayName,
    kind,
    command,
    startupFrames,
    activeFrames,
    recoveryFrames,
    damage,
    hitstunFrames,
    blockstunFrames: 7,
    meterGain: damage * 2,
    meterCost: 0,
    animation: {
      atlas,
      startFrame,
      frameCount,
      framesPerSecond: 16,
      looping: false,
    },
  };
}
function normals(): readonly MoveDefinition[] {
  return [
    combatMove(
      "standing-light",
      "Standing Light",
      "normal",
      ["light"],
      "combat",
      0,
      4,
      5,
      3,
      8,
      6,
      12,
    ),
    combatMove(
      "standing-heavy",
      "Standing Heavy",
      "normal",
      ["heavy"],
      "combat",
      4,
      4,
      10,
      5,
      13,
      11,
      23,
    ),
  ];
}
function special(
  values: Special,
  command: "special1" | "special2",
): MoveDefinition {
  const [id, name, atlas, damage, startup, active, recovery, hitstun] = values;
  return combatMove(
    id,
    name,
    "special",
    [command],
    atlas,
    0,
    16,
    startup,
    active,
    recovery,
    damage,
    hitstun,
  );
}
function artwork(id: FighterId, version: number): FighterDefinition["assets"] {
  const query = `?v=${version}`;
  return {
    canonicalModel: `source-assets/canonical-models-v16/${id}.png`,
    legacyRuntime: `dist/assets/fighters/${id}.webp${id === "jarjacha" ? query : ""}`,
    selection: `dist/assets/fighters/select-v16/${id}.webp${query}`,
    portrait: `dist/assets/fighters/portraits-v16/${id}.webp${query}`,
  };
}

